grand_total = sum(s[1] for s in summary)

def write_csv(path):
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["กิจกรรม", "รายละเอียดค่าใช้จ่าย", "หน่วย", "จำนวน", "ราคาต่อหน่วย (บาท)", "รวม (บาท)", "หมายเหตุ"])
        for r in rows:
            act, detail, unit, qty, price, note = r
            w.writerow([act, detail, unit, qty, price, qty * price, note])
        w.writerow([])
        w.writerow(["สรุปยอดรวมตามกิจกรรม", "", "", "", "", "", ""])
        for act, total in summary:
            w.writerow([act, "", "", "", "", total, ""])
        w.writerow(["ยอดรวมทั้งโครงการ (Grand Total)", "", "", "", "", grand_total, ""])

def try_xlsx(path):
    try:
        import openpyxl
        from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
        from openpyxl.utils import get_column_letter

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Cost Breakdown"

        header_fill = PatternFill("solid", fgColor="1F4E78")
        header_font = Font(bold=True, color="FFFFFF", size=11)
        title_font = Font(bold=True, size=14, color="1F4E78")
        thin = Side(style="thin", color="B0B0B0")
        border = Border(left=thin, right=thin, top=thin, bottom=thin)

        # Title
        ws.merge_cells("A1:G1")
        ws["A1"] = "Cost Breakdown: โครงการพัฒนาผลิตภัณฑ์เชิงอุตสาหกรรมสร้างสรรค์ (สถานประกอบการไม่น้อยกว่า 20 กิจการ)"
        ws["A1"].font = title_font
        ws["A1"].alignment = Alignment(horizontal="left", vertical="center")
        ws.row_dimensions[1].height = 24

        ws.merge_cells("A2:G2")
        ws["A2"] = "สกุลเงิน: บาท (THB) | ตัวเลขเป็นงบประมาณประมาณการ ควรปรับตามใบเสนอราคาจริง"
        ws["A2"].font = Font(italic=True, size=10, color="555555")

        headers = ["กิจกรรม", "รายละเอียดค่าใช้จ่าย", "หน่วย", "จำนวน", "ราคาต่อหน่วย (บาท)", "รวม (บาท)", "หมายเหตุ"]
        r0 = 4
        for c, h in enumerate(headers, 1):
            cell = ws.cell(row=r0, column=c, value=h)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = border

        r = r0 + 1
        for act, detail, unit, qty, price, note in rows:
            ws.cell(row=r, column=1, value=act)
            ws.cell(row=r, column=2, value=detail)
            ws.cell(row=r, column=3, value=unit)
            ws.cell(row=r, column=4, value=qty)
            cell_price = ws.cell(row=r, column=5, value=price)
            cell_price.number_format = '#,##0.00'
            cell_total = ws.cell(row=r, column=6, value=f"=D{r}*E{r}")
            cell_total.number_format = '#,##0.00'
            ws.cell(row=r, column=7, value=note)
            for c in range(1, 8):
                ws.cell(row=r, column=c).border = border
                ws.cell(row=r, column=c).alignment = Alignment(vertical="center", wrap_text=True)
            r += 1

        # Summary section
        r += 1
        ws.cell(row=r, column=1, value="สรุปยอดรวมตามกิจกรรม").font = Font(bold=True, size=12, color="1F4E78")
        r += 1
        for act, total in summary:
            ws.cell(row=r, column=1, value=act)
            cell = ws.cell(row=r, column=6, value=total)
            cell.number_format = '#,##0.00'
            cell.font = Font(bold=True)
            r += 1

        ws.cell(row=r, column=1, value="ยอดรวมทั้งโครงการ (Grand Total)").font = Font(bold=True, size=12, color="C00000")
        cell = ws.cell(row=r, column=6, value=f"=SUM(F{r0+1}:F{r0+{len(rows)}})")
        cell.number_format = '#,##0.00'
        cell.font = Font(bold=True, size=12, color="C00000")

        widths = [38, 52, 12, 10, 16, 14, 34]
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w

        # Freeze header
        ws.freeze_panes = f"A{r0+1}"
        wb.save(path)
        return True
    except Exception as e:
        print("openpyxl not available or error:", e)
        return False

os.makedirs(os.path.dirname(OUT_XLSX) or ".", exist_ok=True)
if not try_xlsx(OUT_XLSX):
    print("Falling back to CSV only.")
write_csv(OUT_CSV)
print(f"Grand Total THB: {grand_total:,}")
print(f"Files: {OUT_XLSX if os.path.exists(OUT_XLSX) else 'N/A'}, {OUT_CSV}")
